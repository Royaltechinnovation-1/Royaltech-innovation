/**
 * Builds src/components/royaltech-home/royaltech-home.css from royaltech-home.source.css.
 *
 *   npm run build:royaltech-home-css
 *
 * The rest of the site does not use Tailwind, so the home page design is compiled once here and
 * committed. Three passes:
 *   1. Tailwind compiles the utilities used by the components in that folder.
 *   2. Cascade layers are flattened (in layer order, un-layered rules last), because the main site's
 *      un-layered CSS would otherwise always beat layered home CSS.
 *   3. Every selector is scoped under `.rt-home` so the home CSS cannot affect other pages.
 */
import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import postcss from "postcss";
import tailwind from "@tailwindcss/postcss";
import prefixSelector from "postcss-prefix-selector";

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const dir = path.join(root, "src", "components", "royaltech-home");
const from = path.join(dir, "royaltech-home.source.css");
const to = path.join(dir, "royaltech-home.css");

const PREFIX = ".rt-home";
const LAYER_ORDER = ["properties", "theme", "base", "components", "utilities"];

/** Pass 2: flatten @layer blocks, keeping layer order and putting un-layered rules last. */
const flattenLayers = () => ({
  postcssPlugin: "flatten-layers",
  Once(css) {
    const buckets = new Map(LAYER_ORDER.map((n) => [n, []]));
    const unlayered = [];
    for (const node of [...css.nodes]) {
      if (node.type === "atrule" && node.name === "layer") {
        if (!node.nodes) {
          node.remove(); // `@layer a, b, c;` order statement
          continue;
        }
        const name = node.params.trim();
        if (!buckets.has(name)) buckets.set(name, []);
        buckets.get(name).push(...node.nodes);
        node.remove();
      } else {
        unlayered.push(node);
        node.remove();
      }
    }
    for (const nodes of [...buckets.values(), unlayered]) {
      for (const n of nodes) css.append(n);
    }
  },
});
flattenLayers.postcss = true;

/** Pass 3: how each selector is scoped. */
function transform(prefix, selector, prefixed) {
  const s = selector.trim();
  // The scope root itself.
  if (s === ":root" || s === ":host" || s === "html" || s === "body") return prefix;
  // Already scoped.
  if (s === prefix || s.startsWith(prefix + " ") || s.startsWith(prefix + ".")) return s;
  // Lenis state classes Lenis sets on <html> while it runs; they stay global.
  if (s.startsWith("html.") || s.startsWith(".lenis")) return s;
  return prefixed;
}

const source = await readFile(from, "utf8");

const compiled = await postcss([tailwind()]).process(source, { from, to });
const flat = await postcss([flattenLayers()]).process(compiled.css, { from: undefined });
const scoped = await postcss([prefixSelector({ prefix: PREFIX, transform })]).process(flat.css, {
  from: undefined,
});

const banner =
  "/* GENERATED by scripts/build-royaltech-home-css.mjs from royaltech-home.source.css. Do not edit by hand. */\n";
await writeFile(to, banner + scoped.css, "utf8");
console.log(`Wrote ${path.relative(root, to)} (${(scoped.css.length / 1024).toFixed(1)} KB)`);
